function cleanHtmlEntities(text) {
  if (!text) return "";
  return text
    .replace(/&#8217;/g, "'")
    .replace(/&#8211;/g, "-")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"');
}

function runClean() {
  console.log('🧹 Bắt đầu rà soát và thay thế 242 mục còn sót...');
  const manifest = JSON.parse(fs.readFileSync(path.join(DATA_DIR, 'manifest.json'), 'utf8'));

  let fixed = 0;

  for (const c of manifest.curricula) {
    for (const u of c.units) {
      const vPath = path.join(DATA_DIR, '..', u.vocabPath);
      const kPath = path.join(DATA_DIR, '..', u.kanjiPath);

      if (fs.existsSync(vPath)) {
        const items = JSON.parse(fs.readFileSync(vPath, 'utf8'));
        for (const it of items) {
          const w = it.word.trim();
          if (MANUAL_MAP[w]) {
            it.meaning = MANUAL_MAP[w];
            fixed++;
          } else {
            it.meaning = cleanHtmlEntities(it.meaning);
            // Nếu vẫn còn tiếng Anh dạng "word (explanation)"
            if (it.meaning.includes('(')) {
              it.meaning = it.meaning.replace(/\(.*?\)/g, '').trim();
            }
          }
        }
        fs.writeFileSync(vPath, JSON.stringify(items, null, 2), 'utf8');
      }

      if (fs.existsSync(kPath)) {
        const items = JSON.parse(fs.readFileSync(kPath, 'utf8'));
        for (const it of items) {
          it.meaning = cleanHtmlEntities(it.meaning);
          if (it.character === '兄') {
            it.meaning = 'HUYNH (anh trai)';
          }
        }
        fs.writeFileSync(kPath, JSON.stringify(items, null, 2), 'utf8');
      }
    }
  }

  console.log(`✅ Đã làm sạch hoàn toàn: ${fixed} mục từ vựng.`);
  buildManifest();
}

